  const dictionaries = { es, en };

  function pickLang(tag) {
    return /^es\b/i.test(String(tag || '')) ? 'es' : 'en';
  }

  function translator(lang) {
    const dict = dictionaries[lang] || en;
    return (key, vars) => {
      const text = dict[key] ?? en[key] ?? key;
      return vars ? text.replace(/\{(\w+)\}/g, (m, name) => (Object.hasOwn(vars, name) ? String(vars[name]) : m)) : text;
    };
  }

  const texts = { dictionaries, pickLang, translator };
  root.VenusApp = Object.assign(root.VenusApp || {}, { texts });
  if (typeof module === 'object' && module.exports) module.exports = texts;
