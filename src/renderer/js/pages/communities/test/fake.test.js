import test from 'node:test';
import assert from 'node:assert/strict';
import { createFakeGroups } from '../../../features/clans/fake.js';
const backend=(scenario='demo')=>createFakeGroups(scenario,{signedIn:()=>true,userId:()=> 'fake-me',onAuth:()=>()=>{}});
test('CRUD configurado es atómico: categorías, cuatro tipos, reordenar y borrar sin perder otros canales', async () => {
  const b=backend(),c=await b.rpc('community_create',{p_name:'Pruebas locales',p_description:'',p_public:true});
  const args={p_community:c.id},category=await b.rpc('community_category_save',{...args,p_name:'Juegos'});
  const created=[];
  for(const kind of ['text','voice','announcement','forum']) created.push(await b.rpc('community_channel_create_configured',{...args,p_kind:kind,p_name:kind,p_patch:{categoryId:category.id,topic:'Tema',icon:'star'}}));
  let state=await b.rpc('community_get',args);
  assert.equal(state.channels.length,6);
  await assert.rejects(b.rpc('community_channel_create_configured',{...args,p_kind:'text',p_name:'mal',p_patch:{slowmodeSeconds:-1}}),{code:'bad_slowmode'});
  assert.equal((await b.rpc('community_get',args)).channels.length,6);
  await b.rpc('community_channels_reorder',{...args,p_ids:state.channels.map(ch=>ch.id).reverse()});
  await b.rpc('community_category_delete',{p_category:category.id});
  state=await b.rpc('community_get',args);
  assert.equal(state.categories.length,0);
  assert.equal(state.channels.length,6);
  assert.ok(state.channels.every(ch=>ch.categoryId===null));
  for(const ch of state.channels) await b.rpc('community_channel_delete',{p_channel:ch.id});
  assert.equal((await b.rpc('community_get',args)).channels.length,0);
});
test('foro persiste tema/respuestas, pagina y borrar raíz deshabilita replies', async () => {
  const b=backend(),topic=await b.rpc('community_forum_topic_create',{p_channel:'f-1',p_title:'Proyecto local',p_body:'Primer mensaje'});
  const reply=await b.rpc('community_forum_reply',{p_topic:topic.id,p_body:'Respuesta'});
  assert.equal(reply.parentId,topic.id);
  const topics=await b.rpc('community_forum_topics',{p_channel:'f-1',p_limit:1});
  assert.equal(topics[0].id,topic.id);assert.equal(topics[0].replyCount,1);
  assert.equal((await b.rpc('community_forum_replies',{p_topic:topic.id}))[0].body,'Respuesta');
  assert.ok((await b.rpc('community_forum_topics',{p_channel:'f-1',p_before:topic.at,p_limit:30})).every(row=>row.id!==topic.id));
  await assert.rejects(b.rpc('community_send',{p_channel:'f-1',p_body:'mensaje'}),{code:'bad_kind'});
  await b.rpc('community_message_delete',{p_id:topic.id});
  await assert.rejects(b.rpc('community_forum_replies',{p_topic:topic.id}),{code:'thread_deleted'});
  await assert.rejects(b.rpc('community_forum_reply',{p_topic:topic.id,p_body:'tarde'}),{code:'thread_deleted'});
});
