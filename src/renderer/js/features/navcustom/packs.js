// Mapa para registerIcons(): { 'px-home': '<path .../>', ..., 'fi-home': ... }
export function packIconMap() {
  const out = {};
  for (const [pack, icons] of Object.entries(PACKS)) for (const [name, svg] of Object.entries(icons)) out[`${PACK_PREFIX[pack]}${name}`] = svg;
  return out;
}

// Nombre del icono a dibujar para un pack: la variante si existe, si no el icono de siempre
export function packIconName(name, pack) {
  const icons = PACKS[pack];
  return icons && Object.prototype.hasOwnProperty.call(icons, name) ? `${PACK_PREFIX[pack]}${name}` : name;
}
