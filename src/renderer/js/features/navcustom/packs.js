// Mapa de 12x12 -> d de un path (rectangulos de 2px por cada tramo de celdas llenas)
export function bitmapPath(rows, cell = 2) {
  const parts = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      let w = 0;
      while (row[x + w] === '#') w++;
      parts.push(`M${x * cell} ${y * cell}h${w * cell}v${cell}h-${w * cell}z`);
      x += w;
    }
  });
  return parts.join('');
}

