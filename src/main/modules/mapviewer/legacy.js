// Mascara del metadato que elige la variante (el resto son orientacion, estado, etc.)
const META_MASK = { 6: 7, 18: 3, 31: 3, 43: 7, 44: 7, 97: 7, 98: 3, 125: 7, 126: 7, 139: 1, 155: 7, 161: 3, 175: 7, 179: 3 };

function legacyName(id, meta) {
  // Troncos: meta & 3 = especie, meta >> 2 = eje (3 = corteza en todas las caras)
  if (id === 17 || id === 162) {
    const species = id === 17 ? WOODS[meta & 3] : WOODS[4 + (meta & 1)];
    const axis = AXES[(meta >> 2) & 3];
    return axis === 'none' ? [`${species}_wood`, null] : [`${species}_log`, { axis }];
  }
  // Mitad de arriba de las plantas dobles: no dice de que planta es
  if (id === 175 && meta >= 8) return ['tall_grass', null];
  const entry = TABLE[id];
  if (entry === undefined) return [id === 0 ? 'air' : `legacy_block_${id}`, null];
  if (typeof entry === 'string') return [entry, null];
  if (entry.length === 2 && typeof entry[1] === 'object' && !Array.isArray(entry[1])) return [entry[0], entry[1]];
  const mask = META_MASK[id] ?? 15;
  return [entry[meta & mask] || entry[0], null];
}

module.exports = { legacyName };
